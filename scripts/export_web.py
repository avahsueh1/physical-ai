#!/usr/bin/env python3
"""Export a trained brain + some held-out courses for the browser page (brain.html).

    python scripts/export_web.py --run runs/full --size tiny
    -> web/brain-model.js     (then open brain.html, or build the one-file version below)
    python scripts/export_web.py --run runs/full --single-file runs/brain-demo.html
"""
import argparse
import json
import os
import sys

import numpy as np

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, ROOT)
from brain.actions import ACTIONS, DECISION_SECONDS, GAIT_NAMES   # noqa: E402
from brain.courses import FAMILIES, make_course                     # noqa: E402
from brain.data import N_DYN                                        # noqa: E402
from brain.env import OBS_NAMES, RAYS                                          # noqa: E402
from brain.policy import CPG, Policy                                # noqa: E402
from brain.world_model import WorldModel                            # noqa: E402


def net_json(net, digits=6):
    r = lambda a: np.round(np.asarray(a, float), digits).tolist()
    return {"act": net.act, "mu": r(net.mu), "sd": r(net.sd),
            "W": [r(W.T) for W in net.W], "b": [r(b) for b in net.b]}


def pick_courses(n=4):
    out = []
    for fam in FAMILIES:
        seeds = list(range(1000, 1000 + n))
        if fam == "gaps":          # make sure both kinds of tunnel are there
            low = [s for s in range(1000, 1100) if not make_course("gaps", s).meta["passable"]][:2]
            high = [s for s in range(1000, 1100) if make_course("gaps", s).meta["passable"]][:2]
            seeds = low + high
        for s in seeds:
            c = make_course(fam, s)
            d = c.to_dict(); d["length"] = c.length
            d["label"] = f"{fam} #{s}" + ((" (too low)" if not c.meta["passable"] else " (fits)") if fam == "gaps" else "")
            out.append(json.loads(json.dumps(d, default=float)))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default="runs/full")
    ap.add_argument("--size", default="tiny")
    ap.add_argument("--out", default=os.path.join(ROOT, "web", "brain-model.js"))
    ap.add_argument("--single-file", default=None, help="also write a self-contained HTML page here")
    a = ap.parse_args()
    pol = Policy.load(os.path.join(a.run, f"policy_{a.size}.npz"))
    wm = WorldModel.load(os.path.join(a.run, "world_model.npz"))
    model = {
        "source": f"{a.run} policy_{a.size}", "decision_seconds": DECISION_SECONDS, "lookahead": 3.0,
        "rays": RAYS, "n_dyn": N_DYN, "goal_sin": OBS_NAMES.index("goal_sin"), "goal_cos": OBS_NAMES.index("goal_cos"), "kappa": 1.0, "margin": 0.2, "use_reflex": bool(pol.use_reflex),
        "actions": [{"name": n, "cmd": c} for n, c in ACTIONS], "gaits": GAIT_NAMES, "cpg": CPG.tolist(),
        "policy": net_json(pol.net), "policy_params": pol.net.n_params,
        "risk": [net_json(m) for m in wm.risk_net.members],
        "courses": pick_courses(),
    }
    js = "// generated by scripts/export_web.py\n(function (r) { const M = " + json.dumps(model, separators=(",", ":")) + \
         ";\n  if (typeof module !== 'undefined' && module.exports) module.exports = M; else r.BRAIN_MODEL = M;\n" \
         "})(typeof window !== 'undefined' ? window : globalThis);\n"
    open(a.out, "w").write(js)
    print(f"wrote {a.out} ({len(js) / 1024:.0f} KB): {len(model['courses'])} courses, "
          f"policy {pol.net.n_params} params, risk ensemble x{len(model['risk'])}")
    if a.single_file:
        html = open(os.path.join(ROOT, "brain.html")).read()
        for src in ("web/core.js", "web/motion.js", "web/terrain.js", "web/brain-web.js", "web/brain-model.js"):
            code = open(os.path.join(ROOT, src)).read() if src != "web/brain-model.js" else js
            html = html.replace(f'<script src="{src}"></script>', "<script>\n" + code.replace("</script", "<\\/script") + "\n</script>")
        html = html.replace('<script src="web/vendor/three.min.js"></script>',
                            '<script src="https://cdnjs.cloudflare.com/ajax/libs/three.js/r128/three.min.js"></script>')
        os.makedirs(os.path.dirname(os.path.abspath(a.single_file)), exist_ok=True)
        open(a.single_file, "w").write(html)
        print(f"wrote {a.single_file} ({len(html) / 1024:.0f} KB, self-contained except three.js from cdnjs)")


if __name__ == "__main__":
    main()
